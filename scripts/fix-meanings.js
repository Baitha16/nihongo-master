// Fix data files
function fixDataFile(filePath) {
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  data.levels.forEach(level => {
    level.questions.forEach(q => {
      // Fix meaning if it's too short or seems incomplete
      const meaning = q.meaning.trim();

      // Check if meaning needs fixing
      if (meaningFixes[meaning.toLowerCase()]) {
        q.meaning = meaningFixes[meaning.toLowerCase()];
      }

      // Ensure options are complete
      q.options = q.options.map(opt => {
        const trimmed = opt.trim();
        if (meaningFixes[trimmed.toLowerCase()]) {
          return meaningFixes[trimmed.toLowerCase()];
        }
        return trimmed;
      });
    });
  });

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf8');
  console.log(`Fixed: ${filePath}`);
}

// Fix all data files
fixDataFile(path.join(dataDir, 'nouns.json'));
fixDataFile(path.join(dataDir, 'verbs.json'));
fixDataFile(path.join(dataDir, 'adjectives.json'));
fixDataFile(path.join(dataDir, 'kanji.json'));

console.log('All data files fixed!');
