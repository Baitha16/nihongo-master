// Add kanji to data
function addKanjiToFile(filePath) {
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  let updated = 0;

  data.levels.forEach(level => {
    level.questions.forEach(q => {
      const reading = q.reading || q.kanji;

      // If kanji is same as reading (all hiragana), try to find kanji
      if (q.kanji === q.reading || !q.kanji) {
        if (kanjiMap[reading]) {
          q.kanji = kanjiMap[reading];
          updated++;
        }
      }
    });
  });

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf8');
  console.log(`Updated ${filePath}: ${updated} entries got kanji`);
}

