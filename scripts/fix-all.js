// Fix data file
function fixDataFile(filePath, categoryName) {
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  let fixed = 0;
  let removed = 0;

  // Fix meanings in all questions
  data.levels.forEach(level => {
    level.questions.forEach(q => {
      // Fix meaning
      const meaning = q.meaning.trim().toLowerCase();
      if (meaningFix[meaning]) {
        q.meaning = meaningFix[meaning];
      }

      // Fix options
      q.options = q.options.map(opt => {
        const optLower = opt.trim().toLowerCase();
        if (meaningFix[optLower]) {
          return meaningFix[optLower];
        }
        return opt;
      });
    });
  });

  // For nouns/verbs/adjectives - remove entries where kanji is same as reading
  // (to avoid duplication with hiragana/katakana quizzes)
  if (categoryName !== 'hiragana' && categoryName !== 'katakana' && categoryName !== 'kanji') {
    data.levels.forEach(level => {
      const originalLength = level.questions.length;
      level.questions = level.questions.filter(q => {
        // Keep if kanji is different from reading (has actual kanji)
        // Or if it's a katakana word
        const isKatakana = /^[\u30A0-\u30FF]+$/.test(q.kanji);
        const hasKanji = q.kanji !== q.reading || isKatakana;
        return hasKanji;
      });
      removed += originalLength - level.questions.length;
    });
  }

  // Regenerate options from same level only
  data.levels.forEach(level => {
    const levelMeanings = level.questions.map(q => q.meaning);

    level.questions.forEach(q => {
      // Get wrong options from same level only
      const otherMeanings = levelMeanings.filter(m => m !== q.meaning);
      const shuffled = otherMeanings.sort(() => 0.5 - Math.random());
      const wrongOptions = shuffled.slice(0, 3);

      // If not enough options from level, add some generic
      if (wrongOptions.length < 3) {
        const generic = ['Makan', 'Minum', 'Tidur', 'Jalan', 'Lari', 'Baca', 'Tulis', 'Duduk', 'Berdiri', 'Pergi'];
        for (const g of generic) {
          if (wrongOptions.length >= 3) break;
          if (g !== q.meaning && !wrongOptions.includes(g)) {
            wrongOptions.push(g);
          }
        }
      }

      const options = [...wrongOptions.slice(0, 3)];
      const correctIndex = Math.floor(Math.random() * 4);
      options.splice(correctIndex, 0, q.meaning);

      q.options = options;
      q.correctIndex = correctIndex;
    });
  });

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf8');
  console.log(`${categoryName}: Fixed meanings, removed ${removed} duplicates, regenerated options`);
}

