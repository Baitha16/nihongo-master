fixDataFile(path.join(dataDir, 'nouns.json'), 'nouns');
fixDataFile(path.join(dataDir, 'verbs.json'), 'verbs');
fixDataFile(path.join(dataDir, 'adjectives.json'), 'adjectives');
fixDataFile(path.join(dataDir, 'kanji.json'), 'kanji');

console.log('\nAll data files fixed!');
