function addFurigana(text) {
  if (!text) return text;
  
  // Sort by length (longest first) for compound matching
  const entries = Object.entries(kanjiMap).filter(e => e[0].length >= 2 && e[1] && e[0] !== e[1]);
  entries.sort((a, b) => b[0].length - a[0].length);
  
  let result = '';
  let i = 0;
  while (i < text.length) {
    let matched = false;
    
    // Try compound words first
    for (const [kanji, reading] of entries) {
      if (text.substring(i, i + kanji.length) === kanji) {
        // Check if already has furigana
        if (i + kanji.length < text.length && text[i + kanji.length] === '(') {
          result += kanji;
          i += kanji.length;
          matched = true;
          break;
        }
        result += kanji + '(' + reading + ')';
        i += kanji.length;
        matched = true;
        break;
      }
    }
    
    if (!matched) {
      const ch = text[i];
      // Check if it's a kanji character
      if (ch.match(/[\u4e00-\u9fff]/) && kanjiMap[ch]) {
        // Check if already has furigana
        if (i + 1 < text.length && text[i + 1] === '(') {
          result += ch;
        } else {
          result += ch + '(' + kanjiMap[ch] + ')';
        }
      } else {
        result += ch;
      }
      i++;
    }
  }
  return result;
}

