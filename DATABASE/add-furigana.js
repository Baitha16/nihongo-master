// ==================== CORE LOGIC ====================
function isKanji(ch) {
  const c = ch.charCodeAt(0);
  return (c >= 0x4e00 && c <= 0x9fff) || (c >= 0x3400 && c <= 0x4dbf);
}

function hasKanji(str) {
  return /[\u4e00-\u9fff\u3400-\u4dbf]/.test(str);
}

function processText(text) {
  if (!text || text.length === 0) return text;
  if (!hasKanji(text)) return text;

  let result = '';
  let i = 0;

  while (i < text.length) {
    const ch = text[i];

    if (isKanji(ch)) {
      // Collect consecutive kanji
      let j = i;
      while (j < text.length && isKanji(text[j])) j++;
      const kanjiRun = text.substring(i, j);

      // Check if followed by (reading) — has existing furigana
      if (j < text.length && text[j] === '(') {
        let close = text.indexOf(')', j);
        if (close !== -1) {
          // Has furigana - keep as is
          result += text.substring(i, close + 1);
          i = close + 1;
          // Skip duplicate: if next is also (reading), skip it
          if (i < text.length && text[i] === '(') {
            let close2 = text.indexOf(')', i);
            if (close2 !== -1) i = close2 + 1;
          }
          continue;
        }
      }

      // Bare kanji — try compound match (entire run)
      const compoundReading = COMPOUND_MAP.get(kanjiRun);
      if (compoundReading) {
        result += kanjiRun + '(' + compoundReading + ')';
        i = j;
        continue;
      }

      // Try matching compound at start of run
      let matched = false;
      for (const [compound, reading] of COMPOUND_MAP) {
        if (kanjiRun.startsWith(compound) && compound.length > 1) {
          result += compound + '(' + reading + ')';
          i += compound.length;
          matched = true;
          break;
        }
      }
      if (matched) continue;

      // Single kanji fallback
      const reading = SINGLE.get(ch);
      if (reading) {
        result += ch + '(' + reading + ')';
      } else {
        result += ch;
      }
      i++;
    } else {
      result += ch;
      i++;
    }
  }

  return result;
}

function isExplanatory(text) {
  if (!text.match(/[\u3040-\u309f\u30a0-\u30ff\u4e00-\u9fff]/)) return true;
  return false;
}

// ==================== MAIN ====================
function main() {
  console.log('Reading:', INPUT_FILE);
  const raw = fs.readFileSync(INPUT_FILE, 'utf-8');
  const data = JSON.parse(raw);

  let updatedCount = 0;
  let totalExamples = 0;
  let skippedNoKanji = 0;
  let skippedExplanation = 0;
  let skippedUnchanged = 0;
  const changes = [];

  for (const bab of data.babs) {
    for (const point of bab.points) {
      if (!point.examples) continue;
      for (const example of point.examples) {
        totalExamples++;
        const originalJp = example.jp;

        if (!hasKanji(originalJp)) {
          skippedNoKanji++;
          continue;
        }

        if (isExplanatory(originalJp)) {
          skippedExplanation++;
          continue;
        }

        const newJp = processText(originalJp);

        if (newJp !== originalJp) {
          example.jp = newJp;
          updatedCount++;
          if (changes.length < 30) {
            changes.push({
              bab: bab.bab,
              point: point.num,
              before: originalJp,
              after: newJp
            });
          }
        } else {
          skippedUnchanged++;
        }
      }
    }
  }

  fs.writeFileSync(INPUT_FILE, JSON.stringify(data, null, 2), 'utf-8');

  console.log('\n=== Furigana Update Results ===');
  console.log(`Total examples scanned: ${totalExamples}`);
  console.log(`Skipped (no kanji): ${skippedNoKanji}`);
  console.log(`Skipped (explanatory): ${skippedExplanation}`);
  console.log(`Skipped (unchanged): ${skippedUnchanged}`);
  console.log(`Updated: ${updatedCount}`);
  console.log('================================');
  console.log('File written successfully!');

  if (changes.length > 0) {
    console.log('\n--- Sample changes ---');
    for (let i = 0; i < Math.min(changes.length, 30); i++) {
      const c = changes[i];
      console.log(`\nBab ${c.bab}, Point ${c.point}:`);
      console.log(`  Before: ${c.before.substring(0, 140)}`);
      console.log(`  After:  ${c.after.substring(0, 140)}`);
    }
  }
}

main();
