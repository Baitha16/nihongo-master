let count = 0;
for (const bab of data.babs) {
  for (const point of bab.points) {
    if (!point.examples) continue;
    for (const ex of point.examples) {
      const orig = ex.jp;
      let jp = orig;

      // Strip parenthesized furigana
      jp = jp.replace(/\([\u3040-\u309f\u30a0-\u30ff\u30fc]+\)/g, '');

      // Replace embedded reading hints
      for (const [hint, replacement] of Object.entries(HINTS)) {
        jp = jp.split(hint).join(replacement);
      }

      if (jp !== orig) {
        ex.jp = jp;
        count++;
      }
    }
  }
}

fs.writeFileSync(INPUT, JSON.stringify(data, null, 2), 'utf-8');
console.log('Stripped + replaced embedded readings in', count, 'entries');
